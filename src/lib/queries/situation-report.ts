export interface SituationReport {
  date: string;
  content: string;
  isAutoGenerated: boolean;
  updatedAt: string;
  updatedByName: string | null;
}

function manilaDateLabel(date: string): string {
  return new Date(`${date}T00:00:00.000Z`).toLocaleDateString("en-PH", {
    timeZone: "Asia/Manila",
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

/** Plain-text draft assembled from on-file stats — a starting point the
 * viewer (ADMIN or WFC Intelligence/M2) always edits by hand before it
 * means anything as an actual report; never presented as a finished
 * report on its own. */
function topByFrequency(values: (string | null)[], limit: number): { label: string; count: number }[] {
  const counts = new Map<string, number>();
  for (const v of values) {
    const label = v?.trim() || "Unspecified";
    counts.set(label, (counts.get(label) ?? 0) + 1);
  }
  return Array.from(counts.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([label, count]) => ({ label, count }));
}

export async function generateSitrepDraft(user: SessionUser, date: string): Promise<string> {
  const data = await getOverviewData(user);
  const { start, end } = reportWindow(date);
  const scopeJtfId = scopeJtfFilter(user, undefined, { allowRollup: true });

  const [
    windowIncidents,
    windowSocialPosts,
    windowIntelRows,
    jtfAssessments,
    allIntelRows,
    socialMonitorData,
  ] = await Promise.all([
    prisma.incident.findMany({
      where: { jtfId: scopeJtfId, date: { gte: start, lt: end } },
      orderBy: { date: "desc" },
      include: { jtf: { select: { id: true, name: true } } },
    }),
    // Social Media Monitor and Intelligence Update are both command-wide
    // (no jtfId of their own) — every ADMIN session (the only role that
    // reaches this generator, see canAccessSituationReport) sees the full
    // picture here regardless of scopeJtfId above.
    prisma.socialMediaPost.findMany({
      where: { postedAt: { gte: start, lt: end } },
      orderBy: { postedAt: "desc" },
    }),
    prisma.intelUpdate.findMany({
      where: { date: { gte: start, lt: end } },
    }),
    // The Overall Assessment section below reuses each dashboard page's own
    // assessment engine rather than re-deriving similar analysis inline —
    // one source of truth per topic, same wording a reader would see on
    // that page itself. These three read all on-file data (not just this
    // reporting window), which is intentional: trend lines and severity
    // calls need more history than one 24h window to mean anything.
    listRecentJtfAssessmentsForDailyAnalysis(),
    listIntelUpdates(user),
    getSocialMonitorData(),
  ]);

  const dailyAssessment = computeDailyAssessment(data, jtfAssessments);
  const intelAssessment = computeIntelAssessment(allIntelRows);
  const socialAssessment = computeSocialMonitorAssessment(socialMonitorData);

  const socialViolent = windowSocialPosts.filter((p) => p.classification === "VIOLENT").length;
  const socialNonViolent = windowSocialPosts.filter((p) => p.classification === "NON_VIOLENT").length;
  const socialUnclassified = windowSocialPosts.length - socialViolent - socialNonViolent;
  const socialHighlighted = windowSocialPosts.filter((p) => p.isHighlighted).length;
  const topSocialTopics = topByFrequency(
    windowSocialPosts.map((p) => (p.topic ? (TOPIC_LABELS[p.topic as SocialPostTopic] ?? p.topic) : null)),
    3
  );

  // windowIncidents is already sorted desc by date, so the first hit per
  // JTF encountered while walking it is that JTF's most recent — one pass,
  // covering every JTF on the roster (not just ones with an incident this
  // period, so a quiet JTF still shows up as "none logged").
  const mostRecentIncidentByJtf = new Map<string, (typeof windowIncidents)[number]>();
  for (const incident of windowIncidents) {
    if (!mostRecentIncidentByJtf.has(incident.jtf.id)) {
      mostRecentIncidentByJtf.set(incident.jtf.id, incident);
    }
  }

  const intelViolent = windowIntelRows.filter((r) => r.category === "VIOLENT").length;
  const intelNonViolent = windowIntelRows.filter((r) => r.category === "NON_VIOLENT").length;
  const topThreatGroups = topByFrequency(
    windowIntelRows.map((r) => r.threatGroup),
    3
  );
  const topIntelProvinces = topByFrequency(
    windowIntelRows.map((r) => r.province),
    3
  );

  const lines: string[] = [];

  lines.push(`DAILY SUMMARY OF REPORTS — ${date}`);
  lines.push(`Reporting Period: ${manilaTimeLabel(start)} to ${manilaTimeLabel(end)} (2200H to 2200H)`);
  lines.push(`Date of Reporting: ${manilaDateLabel(date)}`);
  lines.push("");
  lines.push("1. INCIDENTS (this reporting period)");
  lines.push(`Logged: ${windowIncidents.length}`);
  lines.push(`Priority/flagged areas (overall): ${data.priorityAreaCount}`);
  lines.push("Most Recent Incident by JTF:");
  for (const j of data.jtfDeployments) {
    const r = mostRecentIncidentByJtf.get(j.jtfId);
    lines.push(
      r
        ? `  - ${j.jtfName}: ${r.type}${r.locationLabel ? `, ${r.locationLabel}` : ""} (${manilaTimeLabel(r.date)})`
        : `  - ${j.jtfName}: none logged this reporting period.`
    );
  }
  lines.push("");
  lines.push("2. SOCIAL MEDIA MONITOR (this reporting period)");
  lines.push(
    `Posts logged: ${windowSocialPosts.length} (${socialViolent} violent, ${socialNonViolent} non-violent, ${socialUnclassified} unclassified)`
  );
  lines.push(`Flagged for review: ${socialHighlighted}`);
  lines.push(
    topSocialTopics.length > 0
      ? `Most-cited topic(s): ${topSocialTopics.map((t) => `${t.label} (${t.count})`).join(", ")}`
      : "Most-cited topic(s): none logged this reporting period."
  );
  lines.push("");
  lines.push("3. INTELLIGENCE UPDATE (this reporting period)");
  lines.push(`Reports logged: ${windowIntelRows.length} (${intelViolent} violent, ${intelNonViolent} non-violent)`);
  lines.push(
    topThreatGroups.length > 0
      ? `Most-cited threat group(s): ${topThreatGroups.map((g) => `${g.label} (${g.count})`).join(", ")}`
      : "Most-cited threat group(s): none logged this reporting period."
  );
  lines.push(
    topIntelProvinces.length > 0
      ? `Most-reported province(s): ${topIntelProvinces.map((p) => `${p.label} (${p.count})`).join(", ")}`
      : "Most-reported province(s): none logged this reporting period."
  );
  lines.push("");
  lines.push("4. DEPLOYMENT");
  lines.push(`Total deployed to polling: ${data.totalDeployed.toLocaleString()}`);
  lines.push(`Total QRF: ${data.totalQrf.toLocaleString()}`);
  for (const j of data.jtfDeployments) {
    lines.push(`  - ${j.jtfName}: ${j.deployedToPolling.toLocaleString()} deployed, ${j.qrf.toLocaleString()} QRF`);
  }
  lines.push("");
  lines.push("5. ELECTION OPERATIONS STATUS");
  lines.push(`Registered voters (BARMM): ${data.totalRegisteredVoters.toLocaleString()}`);
  for (const stage of data.electionOpsFunnel) {
    lines.push(`  - ${stage.label}: ${stage.count.toLocaleString()}`);
  }
  lines.push("");
  lines.push("6. OVERALL ASSESSMENT");
  const totalReports = windowIncidents.length + windowSocialPosts.length + windowIntelRows.length;
  lines.push(
    `${totalReports.toLocaleString()} total report(s) this reporting period — ${windowIncidents.length.toLocaleString()} incident(s), ${windowSocialPosts.length.toLocaleString()} social media post(s), ${windowIntelRows.length.toLocaleString()} intelligence report(s).`
  );
  lines.push(`Command-wide severity call (Overview/Daily Analysis): ${dailyAssessment.severityLevel}`);
  lines.push("");
  lines.push("From Overview / Daily Analysis:");
  for (const line of dailyAssessment.analysis) lines.push(`  - ${line}`);
  if (dailyAssessment.recommendations.strategic[0]) {
    lines.push(`  - Top strategic recommendation: ${dailyAssessment.recommendations.strategic[0]}`);
  }
  lines.push("");
  lines.push("From Intelligence Update:");
  for (const line of intelAssessment.analysis) lines.push(`  - ${line}`);
  lines.push("");
  lines.push("From Social Media Monitor:");
  for (const line of socialAssessment.analysis) lines.push(`  - ${line}`);
  lines.push("");
  lines.push("[Add narrative assessment here]");

  return lines.join("\n");
}

export async function getSituationReport(
  user: SessionUser,
  date: string = todayManilaIso()
): Promise<SituationReport> {
  const existing = await prisma.situationReport.findUnique({
    where: { date },
    include: { updatedBy: { select: { name: true } } },
  });
  if (existing) {
    return {
      date: existing.date,
      content: existing.content,
      isAutoGenerated: existing.isAutoGenerated,
      updatedAt: existing.updatedAt.toISOString(),
      updatedByName: existing.updatedBy?.name ?? null,
    };
  }

  const content = await generateSitrepDraft(user, date);
  return {
    date,
    content,
    isAutoGenerated: true,
    updatedAt: new Date().toISOString(),
    updatedByName: null,
  };
}
